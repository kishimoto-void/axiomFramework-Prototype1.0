#[cfg(test)]
mod tests {
    use super::*;
    use axiom_plp::{Annotation, CanonicalState, PAYLOAD_VERSION};
    use std::collections::BTreeMap;

    fn capsule(
        id: &str,
        raw: &str,
        raw_h: &str,
        can_h: &str,
        anns: Vec<(String, String)>,
    ) -> Capsule {
        let annotations: Vec<Annotation> = anns
            .into_iter()
            .map(|(k, v)| Annotation {
                kind: k,
                value: v,
                key: None,
            })
            .collect();
        let mut meta = BTreeMap::new();
        meta.insert(
            "annotation_status".into(),
            "canonical_projection_candidate".into(),
        );
        Capsule {
            id: id.into(),
            raw_text: raw.into(),
            raw_hash: raw_h.into(),
            canonical_hash: can_h.into(),
            canonical: CanonicalState {
                version: PAYLOAD_VERSION.into(),
                language: "en".into(),
                tokens: vec![],
                annotations,
                meta,
            },
        }
    }

    #[test]
    fn matrix_none() {
        let e = DualHashEvaluation::evaluate_hashes_only(
            &DualHashSnapshot::from_pair("A", "B"),
            &DualHashSnapshot::from_pair("A", "B"),
        );
        assert_eq!(e.class, DualHashClass::None);
        assert_eq!(e.primary_kind, DifferenceKind::None);
    }

    #[test]
    fn matrix_semantic() {
        let e = DualHashEvaluation::evaluate_hashes_only(
            &DualHashSnapshot::from_pair("A", "B1"),
            &DualHashSnapshot::from_pair("A", "B2"),
        );
        assert_eq!(e.class, DualHashClass::Semantic);
        assert_eq!(e.primary_kind, DifferenceKind::Semantic);
    }

    #[test]
    fn matrix_state() {
        let e = DualHashEvaluation::evaluate_hashes_only(
            &DualHashSnapshot::from_pair("A1", "B"),
            &DualHashSnapshot::from_pair("A2", "B"),
        );
        assert_eq!(e.class, DualHashClass::State);
    }

    #[test]
    fn matrix_compound() {
        let e = DualHashEvaluation::evaluate_hashes_only(
            &DualHashSnapshot::from_pair("A1", "B1"),
            &DualHashSnapshot::from_pair("A2", "B2"),
        );
        assert_eq!(e.class, DualHashClass::Compound);
    }

    #[test]
    fn constraint_priority() {
        let base = DualHashSnapshot::new(HashA::new("capsule_abc"), HashB::new("out_v1"));
        let cur = DualHashSnapshot::new(HashA::new("capsule_abc"), HashB::new("out_v2"));
        let ev = DualHashEvaluation::evaluate(&base, &cur, Some(false));
        assert_eq!(ev.class, DualHashClass::Semantic);
        assert_eq!(ev.primary_kind, DifferenceKind::Constraint);
    }

    #[test]
    fn capsule_report_semantic() {
        let l = capsule(
            "L",
            "enable bot",
            "raw_same",
            "can_v1",
            vec![("ACTION".into(), "enable".into())],
        );
        let r = capsule(
            "R",
            "enable bot",
            "raw_same",
            "can_v2",
            vec![("ACTION".into(), "publish".into())],
        );
        let rep = report(&l, &r);
        assert_eq!(rep.dual_hash.class, DualHashClass::Semantic);
        assert!(rep.metrics.divergence > 0.0);
        assert!(rep.summary.contains("Semantic"));
    }
}
